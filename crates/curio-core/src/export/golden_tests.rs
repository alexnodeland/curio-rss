//! Byte-for-byte goldens for note frontmatter (`curio.frontmatter.v1`).
//!
//! The frontmatter bytes are part of the published contract, and the
//! managed-region checksum makes every unexpected byte change visible in a
//! user's vault. These goldens pin the exact YAML Curio writes so a change
//! of YAML implementation (issue #180) or of dependency version cannot
//! silently re-quote, re-order or re-indent a single key.
//!
//! Layout (`fixtures/export/frontmatter/`):
//!
//! - `render/<case>.json` — an [`ArticleFrontmatter`] as JSON; the note
//!   [`render_note`] writes for it (body [`BODY`]) is `render/<case>.md`,
//!   and parsing that note back yields the same frontmatter.
//! - `reexport/<case>.edited.md` — a note as a user left it (comments,
//!   flow style, anchors, odd quoting, hand-edited Curio keys);
//!   re-exporting it with `reexport/fresh.json` (body [`BODY`]) writes
//!   `reexport/<case>.md`, and re-exporting *that* changes nothing.
//!
//! The expected `.md` files were generated by the YAML implementation the
//! notes in users' vaults were written with (`serde_yaml` 0.9) — they are
//! the compatibility baseline, never regenerated to match new output.
//! `reexport/tabs-and-wrapping` (TAB separators, wrapped quoted scalars and
//! flow lists, an unseparated comment) came after the switch: `serde_yaml`
//! 0.9 read its edited frontmatter into exactly the values its `.md`
//! carries.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::fs;
use std::path::{Path, PathBuf};

use curio_types::ArticleFrontmatter;

use super::note::{parse_note, render_note, replace_managed};

/// The managed-region body every golden is rendered with.
const BODY: &str = "Body line one.\n\nBody line two.";

fn golden_dir(sub: &str) -> PathBuf {
    let Some(dir) = std::env::var_os("CARGO_MANIFEST_DIR") else {
        panic!("CARGO_MANIFEST_DIR unset: run the tests through cargo");
    };
    PathBuf::from(dir)
        .join("../../fixtures/export/frontmatter")
        .join(sub)
}

fn read(path: &Path) -> String {
    fs::read_to_string(path).unwrap_or_else(|err| panic!("read {}: {err}", path.display()))
}

fn frontmatter(path: &Path) -> ArticleFrontmatter {
    serde_json::from_str(&read(path)).unwrap_or_else(|err| panic!("{}: {err}", path.display()))
}

/// Every file in `dir` whose name ends with `suffix`, sorted.
fn cases(dir: &Path, suffix: &str) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.ends_with(suffix))
        })
        .collect();
    found.sort();
    found
}

/// `input` with `suffix` replaced by `.md`.
fn expected_path(input: &Path, suffix: &str) -> PathBuf {
    let name = input.file_name().unwrap().to_str().unwrap();
    input.with_file_name(format!("{}.md", name.strip_suffix(suffix).unwrap()))
}

#[test]
fn rendered_notes_match_their_goldens_byte_for_byte() {
    let dir = golden_dir("render");
    let inputs = cases(&dir, ".json");
    assert!(
        inputs.len() >= 5,
        "render goldens missing from {}",
        dir.display()
    );
    for input in inputs {
        let fm = frontmatter(&input);
        let expected_file = expected_path(&input, ".json");
        let expected = read(&expected_file);
        let rendered = render_note(&fm, BODY).unwrap();
        assert!(
            rendered == expected,
            "{} drifted from its golden:\n--- expected\n{expected}\n--- rendered\n{rendered}",
            expected_file.display()
        );

        let (_, parsed) = parse_note(&expected, &expected_file).unwrap();
        assert_eq!(
            parsed,
            fm,
            "{} does not parse back",
            expected_file.display()
        );
    }
}

#[test]
fn hand_edited_notes_reexport_to_their_goldens_byte_for_byte() {
    let dir = golden_dir("reexport");
    let fresh = frontmatter(&dir.join("fresh.json"));
    let inputs = cases(&dir, ".edited.md");
    assert!(
        inputs.len() >= 5,
        "re-export goldens missing from {}",
        dir.display()
    );
    for input in inputs {
        let edited = read(&input);
        let expected_file = expected_path(&input, ".edited.md");
        let expected = read(&expected_file);
        let rewritten = replace_managed(&edited, &fresh, BODY, &input).unwrap();
        assert!(
            rewritten == expected,
            "{} drifted from its golden:\n--- expected\n{expected}\n--- rewritten\n{rewritten}",
            expected_file.display()
        );

        // A second re-export of Curio's own output is a fixed point.
        let again = replace_managed(&expected, &fresh, BODY, &expected_file).unwrap();
        assert_eq!(again, expected, "{} is not stable", expected_file.display());
    }
}
